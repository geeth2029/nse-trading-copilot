/**
 * Domain types for NSE Trading Copilot.
 * Strictly adheres to docs/architecture.md and business rules.
 */

export type Exchange = 'NSE';

export type PositionLifecycleStatus = 'ACTIVE' | 'COMPLETED' | 'ARCHIVED';

export type TradeEntryType = 'INITIAL_ENTRY' | 'PYRAMID_ENTRY' | 'POSITION_EXIT';

export type SizingStatus = 'VALID' | 'INVALID_RPS_WARNING' | 'UNAVAILABLE';

export interface Instrument {
  canonicalSymbol: string;   // e.g. "RELIANCE.NS"
  symbol: string;            // e.g. "RELIANCE"
  displayName: string;       // e.g. "Reliance Industries Ltd"
  exchange: Exchange;        // Always 'NSE'
  isLargeCap: boolean;       // AMFI/SEBI Top-100 classification
  sector?: string;           // e.g. "Energy / Conglomerate"
}

export interface MarketSnapshot {
  symbol: string;
  referencePrice: number;            // Displayed current reference share price
  referencePriceAsOf: string;        // Formatted timestamp, e.g. "2026-10-23 15:30:00 IST"
  latestCompletedWeeklyCandleDate: string; // e.g. "2026-10-16"
  twentyWeekSma: number;             // 20-week SMA calculated from the completed weekly candle
  weeklyRsi: number;                 // Weekly RSI (Strict threshold: > 60.0)
  dataSource: string;                // e.g. "Sample NSE Fixture (Demo)"
  isStale?: boolean;
}

/**
 * Authoritative market data snapshot response from backend GET /api/v1/market-data/snapshot/{symbol}.
 * Generated by verified Upstox provider with completed weekly candle indicators.
 */
export interface MarketSnapshotRead {
  symbol: string;
  instrumentIdentifier: string;
  lastPrice: number;
  quoteTimestamp: string;
  twentyWeekSma: number | null;
  weeklyRsi: number | null;
  latestCompletedCandleDate: string | null;
  completedCandlesCount: number;
  isStale: boolean;
  isEligibleForInitial: boolean;
  statusReason?: string | null;
  source: string;
}

export interface ScreenerStock extends Instrument, MarketSnapshot {
  isEligible: boolean;               // True only if weeklyRsi > 60 and price > twentyWeekSma
  eligibilityReasons: string[];      // Explanatory breakdown
  previousClosePrice: number;
  dayChangePercent: number;
  marketCapRank?: number;            // 1-100 Large-Cap rank
}

export type UniverseStatusType = 'VALID' | 'EXPIRED' | 'NOT_YET_ACTIVE' | 'INVALID' | 'UNAVAILABLE';

/**
 * Large-cap universe status contract matching backend UniverseStatusRead.
 */
export interface UniverseStatusRead {
  isAvailable: boolean;
  isValidForDate: boolean;
  status: UniverseStatusType;
  datasetVersion?: string | null;
  sourcePeriodLabel?: string | null;
  classificationPeriod?: string | null;
  effectiveFrom?: string | null;
  effectiveTo?: string | null;
  constituentCount: number;
  statusReason: string;
}

export type ConstituentDiagnosticStatus =
  | 'QUALIFIED'
  | 'NOT_QUALIFIED'
  | 'STALE_QUOTE'
  | 'INSUFFICIENT_HISTORY'
  | 'INDICATORS_UNAVAILABLE'
  | 'QUOTE_UNAVAILABLE'
  | 'PROVIDER_ERROR';

/**
 * Individual constituent screening result matching backend ConstituentScreenResultRead.
 */
export interface ConstituentScreenResultRead {
  rank: number;
  companyName: string;
  isin: string;
  canonicalNseSymbol: string;
  upstoxInstrumentKey: string;
  lastPrice: number | null;
  quoteTimestamp: string | null;
  twentyWeekSma: number | null;
  weeklyRsi: number | null;
  latestCompletedCandleDate: string | null;
  isStale: boolean;
  isQualified: boolean;
  diagnosticStatus: ConstituentDiagnosticStatus | string;
  diagnosticReason?: string | null;
}

/**
 * Bulk screener response matching backend UniverseScreenResponse.
 */
export interface UniverseScreenResponse {
  universeVersion: string;
  classificationPeriod: string;
  sourcePeriodLabel?: string | null;
  evaluatedAt: string;
  totalConstituents: number;
  qualifiedCount: number;
  marketDataSource?: string | null;
  results: ConstituentScreenResultRead[];
}

export interface TradeCalculationInputs {
  userCapital: number;               // Total trading capital allocated
  referencePrice: number;            // Current Reference Share Price
  twentyWeekSma: number;             // 20-week SMA (Stop Loss)
}

export interface TradeCalculationResult {
  rpt: number;                       // Risk Per Trade: User Capital * 0.01
  entryPrice: number;                // Reference Entry Price
  stopLoss: number;                  // 20-week SMA
  rps: number;                       // Risk Per Share: Entry Price - Stop Loss
  quantity: number | null;           // floor(RPT / RPS) when RPS > 0, else null
  sizingStatus: SizingStatus;
  warningMessage?: string;
  capitalRequired: number | null;    // quantity * entryPrice
}

export interface PyramidingEligibilityCheck {
  weeklyRsi: number;
  twentyWeekSma: number;
  previousEntryPrice: number;
  rsiConditionMet: boolean;          // weeklyRsi > 60 (strictly greater)
  smaConditionMet: boolean;          // previousEntryPrice <= twentyWeekSma <= previousEntryPrice + 3
  isEligible: boolean;               // Both must be true
  reasons: string[];
}

export interface TradeEntry {
  id: string;
  positionId: string;
  sequence: number;                  // 1 = initial entry, 2+ = pyramid entries
  entryType: 'INITIAL_ENTRY' | 'PYRAMID_ENTRY';
  entryDate: string;                 // e.g. "2026-10-24"
  entryPrice: number;                // Reference Entry Price (immutable snapshot)
  executionPrice?: number | null;    // Recorded execution purchase price
  priceSource?: 'EXPLICIT_EXECUTION' | 'CONFIRMED_REFERENCE' | string | null;
  stopLoss: number;                  // 20-week SMA at entry time (immutable snapshot)
  rps: number;                       // Entry Price - Stop Loss
  rpt: number;                       // 1% Risk Per Trade snapshot
  quantity: number | null;           // whole shares or null if invalid sizing
  capitalSnapshot: number;           // Capital input snapshot
  sizingStatus: SizingStatus;
  entryPnl?: number | null;          // Calculated when exit is recorded: (exitPrice - entryPrice) * quantity
  notes?: string | null;
}

export interface PositionExit {
  id?: string;
  positionId?: string;
  exitPrice: number;                 // Single exit price for entire accumulated position
  exitDate: string;                  // Recorded exit date
  recordedAt?: string;               // Timestamp when exit was recorded
  notes?: string | null;
}

export interface PortfolioPosition {
  id: string;
  symbol: string;
  companyName: string;
  status: PositionLifecycleStatus;
  initialEntryDate: string;
  entries: TradeEntry[];             // Multiple entries for the same stock
  accumulatedQuantity: number;       // Sum of valid whole shares
  averageEntryPrice: number | null;  // Weighted average entry price across valid entries
  totalCapitalDeployed: number;      // Sum of (entryPrice * quantity)
  currentReferencePrice: number | null; // Reference share price (nullable from backend)
  twentyWeekSmaStopLoss: number | null; // 20-week SMA (nullable from backend)
  latestWeeklyRsi: number | null;       // Weekly RSI (nullable from backend)
  isPyramidEligible: boolean | null;    // Dynamic check against most recent entry row (nullable from backend)
  pyramidCheck?: PyramidingEligibilityCheck | null;
  exit?: PositionExit | null;        // Single exit for entire position
  realizedPnl?: number | null;       // Consolidated gross P&L when exit is recorded
  unrealizedPnl?: number | null;     // (currentReferencePrice - averageEntryPrice) * accumulatedQuantity
  archivedAt?: string | null;
  archiveReason?: string | null;
  createdAt?: string;
  userCapitalAtCreation?: number | null;
}

